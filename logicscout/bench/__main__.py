"""Bench CLI. Example:

uv run python -m logicscout.bench --world relay --seeds 2 \
    --arms full,random_probe,zero_shot,prompt_only,no_briefing,no_transfer,no_adaptation,reasoning_control \
    --out data/bench
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
import time
import traceback
from pathlib import Path

from logicscout import config
from logicscout.bench.baselines import ARMS, ArmContext, estimate_calls, run_arm
from logicscout.referee.referee import cases_for, world_class

RESULTS_MD = config.ROOT / "docs" / "results.md"


def ensure_gate(world_id: str) -> None:
    if world_id != "gate":
        return
    import httpx

    try:
        httpx.get(config.GATE_URL.rstrip("/") + "/", timeout=2.0)
    except httpx.HTTPError:
        from logicscout.worlds import gate_service

        config.GATE_URL = gate_service.start_in_thread()
        print(f"gate service was not running; started in-process at {config.GATE_URL}")


def _fmt(v, nd: int = 2) -> str:
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


COLUMNS = [
    ("world", lambda r: r["world"]), ("arm", lambda r: r["arm"]), ("seed", lambda r: r["seed"]),
    ("status", lambda r: r.get("status")),
    ("held-out success", lambda r: _fmt(r.get("success"))),
    ("subset success (capped)", lambda r: _fmt(r.get("subset_success"))),
    ("compiled on subset", lambda r: _fmt((r.get("compiled") or {}).get("subset_success"))),
    ("random / idle", lambda r: f"{_fmt(r.get('random'))} / {_fmt(r.get('idle'))}" if "random" in r else "-"),
    ("pred acc / persistence", lambda r: f"{_fmt(r.get('prediction_accuracy'))} / {_fmt(r.get('persistence_accuracy'))}"
     if "prediction_accuracy" in r else "-"),
    ("probes", lambda r: _fmt(r.get("probes_used"))),
    ("probes to competence", lambda r: _fmt(r.get("probes_to_competence"))),
    ("recovered / true success after shift", lambda r: (
        f"{_fmt((r.get('recovery') or {}).get('recovered'))} / "
        f"{_fmt((r.get('recovery') or {}).get('true_success_after_shift'))}") if r.get("recovery") else "-"),
    ("false concl. (refuted / held-out contradicted)", lambda r: (
        f"{_fmt(r['false_conclusions'].get('rules_refuted_in_run'))} / "
        f"{_fmt(r['false_conclusions'].get('held_out_contradictions'))}") if r.get("false_conclusions") else "-"),
    ("model calls", lambda r: _fmt(r.get("model_calls"))),
    ("API fail rate", lambda r: _fmt(r.get("failure_rate"))),
    ("tokens", lambda r: _fmt(r.get("tokens"))),
    ("model latency s", lambda r: _fmt(r.get("latency_s"), 1)),
    ("control actions", lambda r: _fmt(r.get("control_actions"))),
    ("wall s", lambda r: _fmt(r.get("wall_s"), 1)),
    ("leakage failures", lambda r: ", ".join(k for k, v in (r.get("leakage_checks") or {}).items()
                                             if v is False) or "none"),
]


def write_results(out: Path, md: Path = RESULTS_MD) -> None:
    rows = []
    for f in sorted(out.rglob("seed-*.json")):
        try:
            rows.append(json.loads(f.read_text(encoding="utf-8")))
        except (OSError, json.JSONDecodeError):
            continue
    rows.sort(key=lambda r: (r["world"], ARMS.index(r["arm"]) if r["arm"] in ARMS else 99, r["seed"]))
    lines = [
        "# LogicScout bench results",
        "",
        "Generated by `python -m logicscout.bench`. Protocol: [evaluation.md](evaluation.md) (written before these "
        "runs). Raw per-seed JSON lives in the bench output directory. n is tiny: these are raw per-seed rows, "
        "not statistics. `held-out success` is the referee's ground-truth success on all held-out cases; "
        "`subset success` is for per-step model arms on the first few referee cases with a step cap "
        "(`compiled on subset` is the compiled playbook on exactly the same cases and cap).",
        "",
        "| " + " | ".join(c for c, _ in COLUMNS) + " |",
        "|" + "---|" * len(COLUMNS),
    ]
    for r in rows:
        lines.append("| " + " | ".join(str(fn(r)).replace("|", "/") for _, fn in COLUMNS) + " |")
    crashes = [r for r in rows if r.get("status") != "ok"]
    if crashes:
        lines += ["", "## Crashes and errors (reported, not dropped)", ""]
        for r in crashes:
            lines.append(f"- {r['world']} / {r['arm']} / seed {r['seed']}: {r.get('status')} - "
                         + "; ".join(str(e)[:300] for e in r.get("errors", [])))
    md.parent.mkdir(parents=True, exist_ok=True)
    md.write_text("\n".join(lines) + "\n", encoding="utf-8")


async def main_async(args: argparse.Namespace) -> int:
    arms = [a.strip() for a in args.arms.split(",") if a.strip()]
    unknown = [a for a in arms if a not in ARMS]
    if unknown:
        print(f"unknown arms {unknown}; known: {ARMS}", file=sys.stderr)
        return 2
    if not config.NEBIUS_API_KEY:
        print("NEBIUS_API_KEY is not set. The bench makes real Nemotron calls and will not run without it "
              "(add it to .env).", file=sys.stderr)
        return 2
    if "full" in arms and "reasoning_control" in arms:  # reasoning_control reuses the full arm's theory
        arms = ["full"] + [a for a in arms if a != "full"]
    ensure_gate(args.world)
    cls = world_class(args.world)
    manual = cls.manual()
    objective_id = args.objective or manual.objectives[0].id
    n_cases = min(args.max_cases, len(cases_for(cls, objective_id)))
    est = {a: estimate_calls(a, manual, n_cases, args.max_steps) for a in arms}
    if "reasoning_control" in arms and "full" not in arms:
        est["reasoning_control"] += estimate_calls("full", manual, n_cases, args.max_steps)
    print(f"bench: world={args.world} objective={objective_id} seeds={args.seeds} arms={arms}")
    print(f"estimated model calls (upper, rough): {est} per seed; total ~{sum(est.values()) * args.seeds}")
    if args.dry_run:
        return 0
    out = Path(args.out)
    for i in range(args.seeds):
        cache: dict = {}
        for arm in arms:
            d = out / args.world / arm / f"seed-{i}"
            d.mkdir(parents=True, exist_ok=True)
            ctx = ArmContext(world_id=args.world, arm=arm, objective_id=objective_id, seed=args.base_seed + i,
                             index=i, out=d, max_cases=args.max_cases, max_steps=args.max_steps, cache=cache)
            t0 = time.perf_counter()
            print(f"[{arm} seed {i}] running...", flush=True)
            try:
                row = await run_arm(arm, ctx)
            except Exception as e:
                row = {"status": "crash", "errors": [f"{type(e).__name__}: {e}"], "traceback": traceback.format_exc()}
            row = {"world": args.world, "arm": arm, "seed": i, "lab_seed": ctx.seed, "objective_id": objective_id,
                   "elapsed_s": round(time.perf_counter() - t0, 1), **row}
            (out / args.world / arm / f"seed-{i}.json").write_text(json.dumps(row, indent=1, default=str),
                                                                   encoding="utf-8")
            print(f"[{arm} seed {i}] {row.get('status')} success={row.get('success', row.get('subset_success'))} "
                  f"calls={row.get('model_calls')} tokens={row.get('tokens')}", flush=True)
            write_results(out, Path(args.results))
    print(f"wrote {args.results}")
    return 0


def main() -> None:
    p = argparse.ArgumentParser(prog="python -m logicscout.bench", description="LogicScout bench (real model calls)")
    p.add_argument("--world", default="relay")
    p.add_argument("--objective", default=None)
    p.add_argument("--seeds", type=int, default=2)
    p.add_argument("--base-seed", type=int, default=7, help="first lab seed; seed i uses base+i")
    p.add_argument("--arms", default=",".join(ARMS))
    p.add_argument("--out", default="data/bench")
    p.add_argument("--results", default=str(RESULTS_MD))
    p.add_argument("--max-cases", type=int, default=2, help="referee cases for per-step model arms")
    p.add_argument("--max-steps", type=int, default=25, help="step cap per case for per-step model arms")
    p.add_argument("--dry-run", action="store_true", help="print the plan and call estimate, run nothing")
    p.add_argument("--report-only", action="store_true", help="rebuild docs/results.md from existing JSON")
    args = p.parse_args()
    if args.report_only:
        write_results(Path(args.out), Path(args.results))
        print(f"wrote {args.results}")
        return
    sys.exit(asyncio.run(main_async(args)))


if __name__ == "__main__":
    main()
